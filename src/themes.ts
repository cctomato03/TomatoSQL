export function getTheme(id: string): Theme {
  return THEMES.find((t) => t.id === id) ?? THEMES[0];
}

export function applyTheme(id: string, fontSize: number, editorFontSize: number) {
  const theme = getTheme(id);
  const root = document.documentElement;
  for (const [k, v] of Object.entries(theme.vars)) {
    root.style.setProperty(k, v);
  }
  root.style.setProperty("--fs", `${fontSize}px`);
  root.style.setProperty("--editor-fs", `${editorFontSize}px`);
  root.style.setProperty("--row-h", `${Math.round(fontSize * 2.0)}px`);
  root.dataset.theme = theme.id;
  root.dataset.colorMode = theme.dark ? "dark" : "light";
}
